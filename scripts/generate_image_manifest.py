"""Regenerate seed-data/project_images_manifest.json from the source image folder.

Project images are NOT in git (see .gitignore) — they live on S3/CDN and the loader
downloads them into MinIO when the backend starts. This manifest is the list of paths
that tells the loader what to download, and tells maintainers what to upload to the CDN.

Re-run whenever images are added to or removed from project-images-source/:
    python scripts/generate_image_manifest.py
"""

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = REPO_ROOT / "project-images-source"
MANIFEST_PATH = REPO_ROOT / "seed-data" / "project_images_manifest.json"

IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".webp"}


def main() -> None:
    if not SOURCE_DIR.exists():
        print(f"[error] {SOURCE_DIR} not found. Download the images from the CDN before generating the manifest.")
        sys.exit(1)

    paths = sorted(
        p.relative_to(SOURCE_DIR).as_posix()
        for p in SOURCE_DIR.rglob("*")
        if p.is_file() and p.suffix.lower() in IMAGE_SUFFIXES
    )
    if not paths:
        print(f"[error] No images found in {SOURCE_DIR}.")
        sys.exit(1)

    total = sum((SOURCE_DIR / p).stat().st_size for p in paths)
    payload = {
        "_comment": (
            "Project image list. The loader downloads <PROJECT_IMAGES_BASE_URL>/<path> into MinIO "
            "at startup. Generated by scripts/generate_image_manifest.py"
        ),
        "count": len(paths),
        "total_bytes": total,
        "images": paths,
    }
    MANIFEST_PATH.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"[ok] Wrote {MANIFEST_PATH.relative_to(REPO_ROOT)}: {len(paths)} images, {total / 1024 / 1024:.1f} MB.")


if __name__ == "__main__":
    main()
